// Copies the backend contract to the frontend verbatim. `--check` fails if they differ (use in CI).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
const SRC = "functions-desk/src/contract.ts";
const DST = "src/desk/api/contract.ts";
const header = "// GENERATED by scripts/sync-desk-contract.mjs from functions-desk/src/contract.ts. DO NOT EDIT.\n";
const want = header + readFileSync(SRC, "utf8");
if (process.argv.includes("--check")) {
  const have = existsSync(DST) ? readFileSync(DST, "utf8") : "";
  if (have !== want) { console.error("desk contract out of sync. Run: npm run desk:sync-contract"); process.exit(1); }
  console.log("desk contract in sync");
} else {
  mkdirSync("src/desk/api", { recursive: true });
  writeFileSync(DST, want);
  console.log("wrote", DST);
}
